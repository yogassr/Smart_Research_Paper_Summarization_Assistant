"""Smart Research Paper Summarization Assistant - Streamlit chat UI.
Run:  streamlit run app.py
"""
import streamlit as st
from dotenv import load_dotenv

load_dotenv()
import analysis  # noqa: E402
import core  # noqa: E402

st.set_page_config(page_title="Paper Assistant", page_icon="📄", layout="wide")

S = st.session_state
if "lib" not in S:
    S.lib = {p.id: p for p in core.load_library()}  # saved papers survive restarts
    S.chats, S.summary = {}, {}
lib = S.lib

GREETING = ("Hi! Ask me to **summarize** this paper, **extract** datasets/methods/results, list its "
            "**limitations**, or ask any question. Answers cite page numbers.")

# ---------------- sidebar: intake + library ----------------
with st.sidebar:
    st.title("📄 Paper Assistant")
    st.caption("Use only papers you are permitted to use. Files stay on this machine.")
    for f in st.file_uploader("Add paper (PDF)", type="pdf", accept_multiple_files=True) or []:
        data = f.getvalue()
        if core.paper_id(data) in lib:
            continue
        bar = st.progress(0, text=f"Reading {f.name}…")
        try:
            p = core.parse_pdf(data, f.name, lambda i, n: bar.progress(i / n, text=f"Page {i}/{n}"))
        except ValueError as e:
            bar.empty()
            st.error(str(e))
            continue
        bar.empty()
        core.save_paper(p)
        lib[p.id] = p
        notes = [f"Loaded **{p.title}** - {p.n_pages} pages, {len(p.sentences)} sentences indexed."]
        if p.unreadable:
            notes.append(f"⚠️ Pages {', '.join(map(str, p.unreadable))} look scanned/unreadable and were skipped.")
        if p.sections_found < 2:
            notes.append("⚠️ Few section headings detected; section boundaries are uncertain.")
        S.chats[p.id] = [{"role": "assistant", "content": "\n\n".join(notes) + "\n\n" + GREETING}]
        S.active = p.id
        st.rerun()

    if lib:
        ids = list(lib)
        active = st.selectbox("Library", ids, format_func=lambda i: lib[i].name, key="active")
        cur = lib[active]
        tags = st.text_input("Tags", value=cur.tags, key=f"tags_{cur.id}")
        if tags != cur.tags:
            cur.tags = tags
            core.save_paper(cur)
        st.download_button("⬇ Export summary (.md)", S.summary.get(cur.id, ""), file_name=f"{cur.id}_summary.md",
                           disabled=cur.id not in S.summary)
        if st.button("🗑 Delete this paper"):
            core.delete_paper(cur)
            lib.pop(cur.id)
            S.chats.pop(cur.id, None)
            S.summary.pop(cur.id, None)
            S.pop("active", None)
            st.rerun()

# ---------------- main: chat ----------------
if not lib:
    st.info("Add a research paper PDF in the sidebar to begin.")
    st.stop()

p = lib[active]
st.subheader(p.title)
st.caption(f"{p.name} · {p.n_pages} pages · {len(p.sentences)} sentences indexed")
chat = S.chats.setdefault(p.id, [{"role": "assistant", "content": GREETING}])


def show(m):
    with st.chat_message(m["role"]):
        if m["role"] == "assistant" and m.get("badge"):
            st.caption(m["badge"])
        if m.get("warning"):
            st.warning(m["warning"])
        st.markdown(m["content"])
        if m.get("evidence"):
            with st.expander(f"Inspect evidence ({len(m['evidence'])} passages)"):
                for e in m["evidence"]:
                    st.markdown(f"> “{e['text']}”  \n> — page {e['page']}, section: {e['section']}")
                st.caption("Verify important claims in the PDF. Human review is required for any decision.")


for m in chat:
    show(m)

c1, c2, c3 = st.columns(3)
if c1.button("Summarize this paper", use_container_width=True):
    S.pending = "Summarize this paper"
if c2.button("Extract datasets, methods & results", use_container_width=True):
    S.pending = "Extract datasets, methods & results"
if c3.button("What are the limitations?", use_container_width=True):
    S.pending = "What are the limitations?"

prompt = st.chat_input("Ask a question about the paper…") or S.pop("pending", None)
if prompt:
    user = {"role": "user", "content": prompt}
    chat.append(user)
    show(user)
    kind = analysis.detect_kind(prompt)
    with st.spinner("Searching the paper…"):
        res = analysis.run(p, kind, prompt)
    bot = {
        "role": "assistant", "content": res.text, "warning": res.warning,
        "badge": "AI-generated · grounded in paper excerpts" if res.ai else "Extractive result (not AI-written)",
        "evidence": [{"text": e.text, "page": e.page, "section": e.section} for e in res.evidence],
    }
    chat.append(bot)
    show(bot)
    if kind == "summary":
        S.summary[p.id] = f"# {p.title}\n\n{res.text}\n\n_Generated by an AI assistant; verify against the paper._\n"
        st.rerun()
